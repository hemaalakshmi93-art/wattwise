import React, { useState } from "react";
import { api } from "../api.js";
import { useAsync } from "../hooks.js";
import { Card, Loading, ErrorBox, Notice, PageHeader } from "../components/ui.jsx";

export default function Missions({ user, version, refresh }) {
  const ch = useAsync(() => api.challenges(user.id), [user.id, version]);
  const prog = useAsync(() => api.progress(user.id), [user.id, version]);
  const recs = useAsync(() => api.recommendations(user.id), [user.id, version]);
  const [msg, setMsg] = useState(null);
  const [busy, setBusy] = useState(null);

  async function complete(c) {
    setBusy(c.id);
    setMsg(null);
    try {
      const res = await api.complete(user.id, c.id);
      setMsg({ tone: "success", text: `Mission complete: +${res.result.points_awarded} points.` });
    } catch (err) {
      setMsg({ tone: "error", text: err.message });
    } finally {
      setBusy(null);
      refresh();
    }
  }

  return (
    <>
      <PageHeader title="Daily Missions">
        Small actions you do yourself. Tick a mission once you have done it. Each mission can earn points once per day.
      </PageHeader>

      {prog.data && (
        <div className="stats three">
          <div className="card stat"><span className="stat-label">Your points</span><span className="stat-value">{prog.data.total_points}</span></div>
          <div className="card stat"><span className="stat-label">Current streak</span><span className="stat-value">{prog.data.current_streak}<small> days</small></span></div>
          <div className="card stat"><span className="stat-label">Missions completed</span><span className="stat-value">{prog.data.completed_count}</span></div>
        </div>
      )}

      {msg && <Notice tone={msg.tone}>{msg.text}</Notice>}

      <Card title={ch.data ? `Missions for ${ch.data.date}` : "Missions"}>
        {ch.loading && !ch.data ? <Loading label="Loading missions" /> : ch.error ? (
          <ErrorBox error={ch.error} onRetry={ch.reload} />
        ) : (
          <ul className="missions">
            {ch.data.challenges.map((c) => (
              <li key={c.id} className={c.completed_today ? "done" : ""}>
                <div className="m-main">
                  <h3>{c.title}</h3>
                  <p>{c.description}</p>
                  <p className="action"><strong>Do this:</strong> {c.action}</p>
                  <p className="muted small">
                    {c.completed_today ? "Completed today. " : ""}
                    {c.last_completed_on ? `Last completed: ${c.last_completed_on}` : "Not completed yet"}
                  </p>
                </div>
                <div className="m-side">
                  <span className="pts">{c.points} pts</span>
                  <button className={`btn ${c.completed_today ? "ghost" : ""}`}
                    disabled={c.completed_today || busy === c.id} onClick={() => complete(c)}>
                    {c.completed_today ? "Done today" : busy === c.id ? "Saving..." : "Mark as done"}
                  </button>
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>

      <Card title="Suggestions based on your data"
        subtitle="Generated by simple rules over your saved readings and household answers. Not AI.">
        {recs.loading && !recs.data ? <Loading /> : recs.error ? <ErrorBox error={recs.error} onRetry={recs.reload} /> : (
          <ul className="recs">
            {recs.data.recommendations.map((r) => (
              <li key={r.id}>
                <strong>{r.title}</strong>
                <span>{r.action}</span>
                <span className="why">Why you see this: {r.why}</span>
              </li>
            ))}
            {recs.data.recommendations.length === 0 && <li className="muted">No suggestions right now.</li>}
          </ul>
        )}
      </Card>
    </>
  );
}
